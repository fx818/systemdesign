import { writeFile } from 'node:fs/promises';
import { createServer } from 'vite';

// Run from app/: node scripts/generate-level-metadata.mjs
const server = await createServer({ server: { middlewareMode: true }, appType: 'custom' });
try {
  const { levels } = await server.ssrLoadModule('/src/content/registry.eager.ts');
  const { toLevelMeta, chapterOf } = await server.ssrLoadModule('/src/content/metadata.ts');
  for (const level of levels) {
    const path = `src/content/ch${chapterOf(level)}/${level.id}/meta.ts`;
    await writeFile(path, `// Generated by scripts/generate-level-metadata.mjs; regenerate after catalog changes.\nimport type { LevelMeta } from '@/content/metadata';\n\nexport default ${JSON.stringify(toLevelMeta(level), null, 2)} satisfies LevelMeta;\n`);
  }
  console.log(`Generated metadata for ${levels.length} levels.`);
} finally {
  await server.close();
}
